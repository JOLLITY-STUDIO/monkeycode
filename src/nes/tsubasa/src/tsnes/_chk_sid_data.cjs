// 3. 从 ROM 中读取实际 PRG bank 数据
console.log('\n3. 从 ROM PRG 数据读取实际 track 内容...');
const prgAll = require('./rom-data/index').NES_PRG_ROM;
// Bank 13 (0xX013) 映射到 $8000-$BFFF. 所以 $918A 在 bank 13
// Bank 13 = indices 13 * 0x2000 to 14 * 0x2000
const BANK_SIZE = 0x2000;
const bank13Offset = 13 * BANK_SIZE;
const bank13Data = prgAll.slice(bank13Offset, bank13Offset + BANK_SIZE);

// ROM 地址 $918A → bank13 偏移 = 0x918A - 0x8000 = 0x118A
function romRead(addr) {
  const offset = addr - 0x8000;
  return bank13Data[offset];
}

const initEntries = [
  { ch: 0, addr: 0x91F4 },
  { ch: 1, addr: 0x9230 },
  { ch: 3, addr: 0x91F3 },
];

for (const e of initEntries) {
  console.log(`\n  ch${e.ch} track @ ROM $${e.addr.toString(16)}:`);
  const data = [];
  let addr = e.addr;
  // Read first 64 bytes of track data
  for (let i = 0; i < 64; i++) {
    const b = romRead(addr + i);
    data.push(b);
    // Stop at terminator
    if (b === 0xFF && i > 2) break;
  }
  console.log(`    [${data.length} bytes] ${data.map(b => '0x' + b.toString(16).padStart(2,'0')).join(' ')}`);
  
  // Check if this data is in CH0 trackBytes
  const ch0Data = [];
  const off0 = e.addr - CH0_TRACK_PTR;
  if (off0 >= 0 && off0 < CH0.length) {
    for (let i = 0; i < Math.min(30, CH0.length - off0); i++) ch0Data.push(CH0[off0 + i]);
    console.log(`    In CH0 trackBytes[${off0}]: ${ch0Data.map(b=>'0x'+b.toString(16).padStart(2,'0')).join(' ')}`);
  } else {
    console.log(`    NOT in CH0 trackBytes (offset ${off0} out of range 0-${CH0.length-1})`);
  }
}

