const BASE = 0x9460;
const POS_NAMES = ['GK', 'DF', 'MF', 'FW'];

function le16(lo, hi) { return lo | (hi << 8); }

// =========== 1. 主指针表 $9460-$9473 ===========
console.log('═══ $9460 指针表 (10 项, 按队伍/场景索引) ═══');
const ptrs = [];
for (let i = 0; i < 10; i++) {
    const ptr = le16(data[i * 2], data[i * 2 + 1]);
    ptrs.push(ptr);
    const offset = ptr - BASE;
    const countPts = ptrs.filter(p => p === ptr).length;
    const dup = countPts > 1 ? ` (与前面重复, ${countPts - 1}项)` : '';
    console.log(`  [${i}] → $${ptr.toString(16).toUpperCase()}  (off=0x${offset.toString(16)})${dup}`);
}

// =========== 2. 解析各指针指向的数据 ===========
console.log('\n═══ 各数据集内容 (4字节记录) ═══');

const seen = new Set();
for (let fi = 0; fi < ptrs.length; fi++) {
    const ptr = ptrs[fi];
    if (seen.has(ptr)) {
        console.log(`\n  [${fi}] $${ptr.toString(16)} → 同上`);
        continue;
    }
    seen.add(ptr);
    const off = ptr - BASE;

    console.log(`\n  [${fi}] $${ptr.toString(16).toUpperCase()}  (off=0x${off.toString(16)}):`);

    // 尝试读取记录，直到数据超出或看起来不合理
    let slots = [];
    let endOff = off;
    for (let s = 0; s < 20; s++) {
        const pos = off + s * 4;
        if (pos + 3 >= data.length) break;
        const b0 = data[pos];
        const b1 = data[pos + 1];
        const b2 = data[pos + 2];
        const b3 = data[pos + 3];
        const posType = b3 & 0x03;
        const flagsHi = (b3 >> 3) & 0x1F;
        const posName = POS_NAMES[posType] || '??';
        slots.push({ b0, b1, b2, b3, posName, flagsHi });
        endOff = pos + 4;

        // 检查是否到了下一个指针区域
        if (pos + 4 < data.length) {
            const nextMaybe = le16(data[pos + 4], data[pos + 5]);
            // 如果下一个位置读到有效指针值，可能已到边界
            if (nextMaybe >= BASE && nextMaybe < BASE + data.length) {
                // 可能是新指针表开始
                break;
            }
        }

        // 连续全零可能到边界
        if (s > 5 && b0 === 0 && b1 === 0 && b2 === 0 && b3 === 0) {
            // 再读两个看看
            const pp1 = pos + 4;
            const pp2 = pos + 8;
            if (pp2 + 3 < data.length) {
                const allZero1 = data[pp1]===0 && data[pp1+1]===0 && data[pp1+2]===0 && data[pp1+3]===0;
                const allZero2 = data[pp2]===0 && data[pp2+1]===0 && data[pp2+2]===0 && data[pp2+3]===0;
                if (allZero1 && allZero2) {
                    // 连续三个全零记录，截断
                    break;
                }
            }
        }
    }

    for (let s = 0; s < slots.length; s++) {
        const slot = slots[s];
        console.log(`    [${String(s).padStart(2)}]: ${slot.b0.toString(16).padStart(2,'0')} ${slot.b1.toString(16).padStart(2,'0')} ${slot.b2.toString(16).padStart(2,'0')} ${slot.b3.toString(16).padStart(2,'0')}  |  raw(${slot.b0.toString(10).padStart(3)},${slot.b1.toString(10).padStart(3)},${slot.b2.toString(10).padStart(3)})  pos=${slot.posName}  flagsHi=${slot.flagsHi}`);
    }
    console.log(`    共计 ${slots.length} 条记录, 数据止于 offset 0x${endOff.toString(16)}`);
}

