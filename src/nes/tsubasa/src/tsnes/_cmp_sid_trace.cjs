// ── SID Sequencer Simulator ──
function simSidSequencer(data, chIdx, maxFrames) {
  const result = []; // { frame, noteIdx, octave, period, noteDesc }
  let pos = 0;
  let durLo = 1, durHi = 1;
  let volCtrl = 0x0F;
  let stack = [];
  let loopCount = 0, loopPos = 0;
  let n = 0; // note sequence counter
  let maxIter = 100000;

  // Skip 0xFF prefix if present
  if (data[pos] === 0xFF) pos++;

  while (pos < data.length && n < maxFrames && maxIter-- > 0) {
    // Decrement duration
    durLo--;
    if (durLo > 0) {
      n++;
      continue; // holding current note
    }
    
    // Duration expired → read next note/command
    while (pos < data.length && maxIter-- > 0) {
      const b = data[pos++];
      
      if (b < 0x80) {
        // Note body
        const noteIdx = b & 0x0F;
        const octave = (b & 0xF0) >> 4;
        
        if (chIdx === 3) {
          // NOISE
          if (b === 0x10) {
            // rest
            durLo = durHi;
            // 无频率输出
          } else {
            const period = b & 0x0F;
            result.push({ frame: n, ch: chIdx, noteIdx: -1, octave: -1, period, raw: b });
          }
        } else {
          // SQ/TRI
          if (noteIdx >= 12) {
            durLo = durHi; // rest
          } else {
            let period = FREQ_TABLE[noteIdx];
            for (let o = 0; o < octave; o++) period >>= 1;
            if (period < 2) period = 2;
            result.push({ frame: n, ch: chIdx, noteIdx, octave, period, raw: b });
          }
        }
        
        durLo = durHi;
        n++;
        break;
      }
      
      if (b >= 0xE0) {
        const cmdIdx = b & 0x1F;
        switch (cmdIdx) {
          case 0x00: // $E0 SET_TIMING
            pos++; // skip timing index
            continue;
          case 0x01: // $E1
            continue;
          case 0x02: // $E2 SET_VOLUME
            volCtrl = (volCtrl & 0xF0) | (data[pos++] & 0x0F);
            continue;
          case 0x03: // $E3 OR_VOLUME_DUTY
            volCtrl |= (data[pos++] & 0x3F);
            continue;
          case 0x04: // $E4 ENABLE_SWEEP
            pos++;
            continue;
          case 0x05: // $E5 SET_PORTAMENTO
            pos++;
            continue;
          case 0x06: // $E6 SET_VIBRATO
            pos++;
            continue;
          case 0x07: // $E7 CLEAR_EFFECT
            continue;
          case 0x08: { // $E8 JUMP
            const lo = data[pos++];
            const hi = data[pos++];
            const target = lo | (hi << 8);
            // 跳转到 ROM 地址 — 在本地数据中无法对应
            pos = data.length; // 终止
            break;
          }
          case 0x09: { // $E9 CALL
            const lo = data[pos++];
            const hi = data[pos++];
            const target = lo | (hi << 8);
            stack.push(pos + 2);
            pos = data.length; // 终止
            break;
          }
          case 0x0A: // $EA RETURN
            if (stack.length > 0) pos = stack.pop();
            else pos = data.length;
            break;
          case 0x0B: // $EB LOOP_START
            loopCount = data[pos++];
            loopPos = pos;
            continue;
          case 0x0C: // $EC LOOP_END
            if (loopCount > 0) {
              loopCount--;
              if (loopCount > 0) pos = loopPos;
              else loopCount = 0;
            }
            continue;
          case 0x0D: // $ED SET_DURATION
            pos++;
            continue;
          case 0x0E: // $EE MUTE
            pos = data.length; // stop
            break;
          case 0x0F: // $EF PLAY_DMC
            continue;
          default:
            continue;
        }
        if (pos >= data.length) break;
        continue;
      }
      
      // $80-$DF: note duration prefix
      const durIdx = b & 0x3F;
      durLo = durHi = (DUR_TABLE[durIdx] || 1);
      continue;
    }
  }
  
  return result;
}

