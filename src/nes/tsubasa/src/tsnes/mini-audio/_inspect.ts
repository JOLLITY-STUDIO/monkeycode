import { NesAudio } from './emu/nes-audio';
const n = new NesAudio();
const cpu = n.cpu as any;
const mmap = n.mmap as any;
console.log('cpu keys:', Object.keys(cpu).slice(0, 30).join(', '));
console.log('cpu.memory type:', typeof cpu.memory, Array.isArray(cpu.memory) ? 'len='+cpu.memory.length : '');
console.log('cpu.REG_PC:', typeof cpu.REG_PC);
console.log('cpu.step:', typeof cpu.step);
console.log('mmap keys:', Object.keys(mmap).slice(0, 20).join(', '));
console.log('mmap._load8kBank:', typeof mmap._load8kBank);
console.log('mmap.prgBankMap:', mmap.prgBankMap);
console.log('frameCount:', n.frameCount);
