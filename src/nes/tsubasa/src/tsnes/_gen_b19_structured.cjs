const fs = require('fs');
const c = fs.readFileSync('game-engine/native-game/tsubasa/banks/prg/bank-19-script-engine-data.ts', 'utf8');

function extractArray(label) {
  const idx = c.indexOf('DATA_' + label);
  if (idx < 0) return [];
  const eqIdx = c.indexOf('=', idx);
  const open = c.indexOf('[', eqIdx);
  if (open < 0) return [];
  let depth = 0, close = open;
  for (let i = open; i < c.length; i++) {
    if (c[i] === '[') depth++;
    else if (c[i] === ']') { depth--; if (depth === 0) { close = i; break; } }
  }
  const arr = c.substring(open + 1, close);
  return (arr.match(/0x[0-9A-Fa-f]{2}/g) || []).map(h => parseInt(h, 16));
}

function hexStr(arr) {
  return arr.map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ');
}

// Concatenate both arrays (same as original code's SCRIPT_DATA)
const d1 = extractArray('$944E_$988E');
const d2 = extractArray('$988F_$9FFF');
const raw = [...d1, ...d2];
console.log('Raw bytes: d1=' + d1.length + ' d2=' + d2.length + ' total=' + raw.length);

// Find E3 terminator position (last E3 in d1 that sits in control-flow position)
let e3Pos = -1;
for (let i = d1.length - 1; i >= 0; i--) {
  if (d1[i] === 0xE3) { e3Pos = i; break; }
}
console.log('Last E3 in d1 at offset $' + e3Pos.toString(16));

// Parse: same byte-level logic as bank19_mainParser
// Stop when we hit FF padding (>= 2 consecutive FF bytes with no useful command)
const commands = [];
const cmdOffsets = []; // byte offset of each command (for jump resolution)
let i = 0;
let ffStreak = 0;

while (i < raw.length) {
  const cmdOffset = i; // snapshot before consuming
  cmdOffsets.push(cmdOffset);
  const byte = raw[i];

  if (byte === 0xFF) {
    ffStreak++;
    i++;
    if (ffStreak >= 4) {
      console.log(`FF padding at offset $${i.toString(16)}, stopping`);
      break;
    }
    commands.push({ type: 'ctrl_unknown', code: 0xFF });
    continue;
  }
  ffStreak = 0;

  if (byte >= 0xE0) {
    i++;
    switch (byte) {
      case 0xE0: {
        if (i >= raw.length) break;
        commands.push({ type: 'ctrl_state', state: raw[i++] });
        break;
      }
      case 0xE1: {
        if (i >= raw.length) break;
        commands.push({ type: 'ctrl_jump', delta: raw[i++] });
        break;
      }
      case 0xE2: {
        if (i + 1 >= raw.length) break;
        commands.push({ type: 'ctrl_set_xy', x: raw[i++], y: raw[i++] });
        break;
      }
      case 0xE3: {
        commands.push({ type: 'ctrl_terminate' });
        i = raw.length;
        break;
      }
      case 0xE4: {
        const tiles = [];
        while (i < raw.length) {
          const b = raw[i];
          if (b >= 0xE0 || b === 0x00 || b === 0xFC) break;
          tiles.push(raw[i++]);
        }
        if (i < raw.length && raw[i] === 0xFC) i++;
        commands.push({ type: 'ctrl_string', tiles });
        break;
      }
      case 0xE5: {
        if (i >= raw.length) break;
        commands.push({ type: 'ctrl_call', routine: raw[i++] });
        break;
      }
      case 0xE6: {
        if (i >= raw.length) break;
        commands.push({ type: 'ctrl_other', param: raw[i++] });
        break;
      }
      default: {
        commands.push({ type: 'ctrl_unknown', code: byte });
        break;
      }
    }
  } else if (byte === 0x00) {
    i++;
    commands.push({ type: 'upload_null' });
  } else {
    const len = byte;
    i++;
    if (i + 2 >= raw.length) break;
    const addrLo = raw[i++];
    const addrHi = raw[i++];
    if (i + len > raw.length) break;
    const tiles = raw.slice(i, i + len);
    i += len;
    commands.push({ type: 'upload', addr: (addrHi << 8) | addrLo, tiles });
  }
}

console.log(`Total commands: ${commands.length}, bytes consumed: ${i}/${raw.length}`);
const counts = {};
commands.forEach(c => { counts[c.type] = (counts[c.type] || 0) + 1; });
console.log(counts);

// Attach byte offset to each command
commands.forEach((cmd, idx) => { cmd._offset = cmdOffsets[idx]; });

// Generate output
let out = `// ═══════════════════════════════════════════════
// Structured script data — pre-parsed from bank-19 raw bytecode stream
// Generated by _gen_b19_structured.cjs
//
// Source: DATA_$944E_$988E (${d1.length}B) + DATA_$988F_$9FFF (${d2.length}B padding)
// Parsed as original bank19_mainParser does: sequential byte-level processing
// ═══════════════════════════════════════════════

/** A bank-19 script command — pre-parsed from raw bytecode stream */
export type Bank19ScriptCommand = Readonly<{
  byteOffset: number;  // original byte position in $944E-$9FFF range (for jump resolution)
}> & (
  | { readonly type: 'upload';        readonly addr: number; readonly tiles: readonly number[] }
  | { readonly type: 'upload_null' }
  | { readonly type: 'ctrl_state';    readonly state: number }          // E0
  | { readonly type: 'ctrl_jump';     readonly delta: number }          // E1
  | { readonly type: 'ctrl_set_xy';   readonly x: number; readonly y: number } // E2
  | { readonly type: 'ctrl_terminate' }                                 // E3
  | { readonly type: 'ctrl_string';   readonly tiles: readonly number[] } // E4
  | { readonly type: 'ctrl_call';     readonly routine: number }        // E5
  | { readonly type: 'ctrl_other';    readonly param: number }          // E6
  | { readonly type: 'ctrl_unknown';  readonly code: number }           // E7+/FF
);

/** Pre-built lookup: byte offset → command index (for ctrl_jump resolution) */
export const BYTE_OFFSET_TO_CMD: ReadonlyMap<number, number> = new Map([
${cmdOffsets.map((off, idx) => `  [${off}, ${idx}],`).join('\n')}
]);

/** Full SCRIPT_DATA parsed → ${commands.length} commands */
export const SCRIPT_COMMANDS: readonly Bank19ScriptCommand[] = [
`;

commands.forEach((cmd, idx) => {
  const off = cmd._offset;
  const offComment = ` // [${idx}] @$0x${off.toString(16).padStart(4, '0')}`;

  switch (cmd.type) {
    case 'upload': {
      const h = '0x' + cmd.addr.toString(16).padStart(4, '0').toUpperCase();
      out += `  { byteOffset: ${off}, type: 'upload', addr: ${h}, tiles: [${hexStr(cmd.tiles)}] },${offComment}\n`;
      break;
    }
    case 'upload_null':
      out += `  { byteOffset: ${off}, type: 'upload_null' },${offComment}\n`;
      break;
    case 'ctrl_state':
      out += `  { byteOffset: ${off}, type: 'ctrl_state', state: 0x${cmd.state.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
    case 'ctrl_jump':
      out += `  { byteOffset: ${off}, type: 'ctrl_jump', delta: 0x${cmd.delta.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
    case 'ctrl_set_xy':
      out += `  { byteOffset: ${off}, type: 'ctrl_set_xy', x: 0x${cmd.x.toString(16).padStart(2, '0')}, y: 0x${cmd.y.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
    case 'ctrl_terminate':
      out += `  { byteOffset: ${off}, type: 'ctrl_terminate' },${offComment}\n`;
      break;
    case 'ctrl_string':
      out += `  { byteOffset: ${off}, type: 'ctrl_string', tiles: [${hexStr(cmd.tiles)}] },${offComment} ${cmd.tiles.length}B\n`;
      break;
    case 'ctrl_call':
      out += `  { byteOffset: ${off}, type: 'ctrl_call', routine: 0x${cmd.routine.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
    case 'ctrl_other':
      out += `  { byteOffset: ${off}, type: 'ctrl_other', param: 0x${cmd.param.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
    case 'ctrl_unknown':
      out += `  { byteOffset: ${off}, type: 'ctrl_unknown', code: 0x${cmd.code.toString(16).padStart(2, '0')} },${offComment}\n`;
      break;
  }
});

out += `];\n`;

fs.writeFileSync('game-engine/native-game/tsubasa/banks/prg/bank-19-script-engine-structured-data.ts', out, 'utf8');
console.log('\nDone! Written bank-19-script-engine-structured-data.ts');
