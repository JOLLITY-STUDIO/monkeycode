export interface BgmSidEntry {
  id: string;
  bank: number;
  type: string;
  chCount: number;
  bytes: number;
  notes: number;
  name?: string;
  desc?: string;
  /** 引擎空轨道（实机即无声） */
  silent?: boolean;
  /** Per-channel track data */
  trackSQ1: readonly number[];
  trackSQ2: readonly number[];
  trackTRI: readonly number[];
  trackNOISE: readonly number[];
  /** Shared raw data for CALL/JUMP NES address resolution */
  raw: readonly number[];
  /** NES 基址 = RAW_START（raw[0] 对应的 NES 地址） */
  nesBase: number;
  /** header 在 raw 内的偏移（initPtr - RAW_START），默认 0 */
  headerOffset?: number;
  /** Whether raw is a real shared BGM header (true for bank-shared raw data). SID tracks should load from split track arrays. */
  useSharedRaw?: boolean;
}

