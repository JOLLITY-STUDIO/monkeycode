/** 阵容球员条目: [位置码, 球员ID] */
export interface RosterPlayerSlot {
  /** 位置码 (0-11, 场上位置) */
  pos: number;
  /** 球员ID (引用 PLAYERS 目录 0x01-0x75) */
  player: number;
}

/** CPU 球队阵容 */
export interface CpuRoster {
  idx: number;
  /** PRG offset */
  offset: number;
  /** CPU 地址 ($BAF8-$BCFE) */
  cpuAddr: number;
  /** GFX 基址 4 字节 */
  gfx: readonly number[];
  /** 队标 3 字节 */
  badge: readonly number[];
  /** 球员槽位 [位置码, 球员ID]×N */
  players: readonly RosterPlayerSlot[];
  /** 原始数据 (含 $0F 终止) */
  raw: readonly number[];
}

/** CPU 球队阵容列表 (解析自 PRG_BANK_29) */
export const CPU_ROSTERS: readonly CpuRoster[] = (() => {
  const list: CpuRoster[] = [];
  const limit = 0x1D00;
  let off = 0x1AF8;
  let idx = 0;
  while (off + 8 < limit) {
    while (off < limit && PRG_BANK_29[off] === 0) off++;
    if (off >= limit || PRG_BANK_29[off] === 0xFF) break;
    const s = off;
    const gfx = PRG_BANK_29.slice(off, off + 4);
    const badge = PRG_BANK_29.slice(off + 4, off + 7);
    off += 7;
    const players: RosterPlayerSlot[] = [];
    while (off < limit && PRG_BANK_29[off] !== 0x0F) {
      players.push({ pos: PRG_BANK_29[off], player: PRG_BANK_29[off + 1] });
      off += 2;
    }
    if (off < limit) off += 1;
    list.push({ idx: idx++, offset: s, cpuAddr: 0xA000 + s, gfx, badge, players, raw: PRG_BANK_29.slice(s, off) });
  }
  return list;
})();

/** 按球队序号取阵容 */
export function getCpuRoster(idx: number): CpuRoster | undefined {
  return CPU_ROSTERS[idx];
}

/** 按指针表目标地址反查阵容 (供 Bank 01 查询) */
export function getRosterByAddr(cpuAddr: number): CpuRoster | undefined {
  return CPU_ROSTERS.find(r => r.cpuAddr === cpuAddr);
}

// ═══════════════════════════════════════════════════════════════
// CPU 地址访问层 (替代 MMC3 $A000-$BFFF 窗口映射)
// ═══════════════════════════════════════════════════════════════
// bank29 数据窗口基址: CPU $A000-$BFFF, PRG offset = cpuAddr - 0xA000
// 只读访问, 供 service 层 (Bank01/Bank30) 翻译消费逻辑使用

/** CPU 地址 → PRG offset (窗口基址 0xA000) */
export function cpuToOffset(cpuAddr: number): number {
  return cpuAddr - 0xA000;
}

/** 读 1 字节 (cpuAddr 必须落在 $A000-$BFFF) */
export function readBank29(cpuAddr: number): number {
  const off = cpuToOffset(cpuAddr);
  if (off < 0 || off >= PRG_BANK_29.length) return 0xFF;
  return PRG_BANK_29[off];
}

/** 读 16 位 LE (bank_01 大量使用 LDA $xxxx / LDY $xxxx+1 指针) */
export function readBank29U16(cpuAddr: number): number {
  return readBank29(cpuAddr) | (readBank29(cpuAddr + 1) << 8);
}

/** 读 16 位 LE 并除以 N (对应 asm LSR/ROR 移位还原指针) */
export function readBank29U16Div(cpuAddr: number, div: number): number {
  return Math.floor(readBank29U16(cpuAddr) / div);
}

