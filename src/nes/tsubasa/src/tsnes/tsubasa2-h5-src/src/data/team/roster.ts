/**
 * 按球队索引取 GFX 基址指针 (bank_01 $8F79: ram_0026=teamId → $BA4C,X*2)
 * 对应 asm: LDA ram_0026 / ASL / TAX / LDA $BA4C,X / STA ram_00E6 / LDA $BA4D,X / STA ram_00E7
 */
export function getTeamGfxBase(teamId: number): number {
  return readBank29U16(ADDR_TEAM_GFX_BASE + teamId * 2);
}

/**
 * 按球队索引取阵容数据 CPU 地址 (bank_01 $8FC2 段)
 * asm: 先经 $B023 索引换算, 再 LDA $BA1C,X → 指向该队阵容数据
 */
export function getRosterAddr(teamId: number, sub: number): number {
  // $8FC2: STX ram_00EC / JSR $B023(读属性) / AND #$F0 / LSR / ADC ram_00EC → X
  // $8FD0: LDA $BA1C,X → 指针表
  return readBank29(ADDR_ROSTER_PTR + teamId + ((sub & 0xF0) >> 4));
}

/** 按球队索引读阵容槽位表项 (bank_01 $8516: LDA $BCD1,X) */
export function getRosterSlot(teamId: number): number {
  return readBank29(ADDR_ROSTER_BY_TEAM + teamId);
}

