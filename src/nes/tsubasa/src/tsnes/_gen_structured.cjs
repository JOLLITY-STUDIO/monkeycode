const fs = require('fs');
const c = fs.readFileSync('game-engine/native-game/tsubasa/banks/prg/bank-01-data.ts', 'utf8');

function extractArray(label) {
  const idx = c.indexOf('DATA_' + label);
  if (idx < 0) return [];
  const eqIdx = c.indexOf('=', idx);
  const open = c.indexOf('[', eqIdx);
  if (open < 0) return [];
  let depth = 0, close = open;
  for (let i = open; i < c.length; i++) {
    if (c[i] === '[') depth++;
    else if (c[i] === ']') { depth--; if (depth === 0) { close = i; break; } }
  }
  const arr = c.substring(open + 1, close);
  return (arr.match(/0x[0-9A-Fa-f]{2}/g) || []).map(h => parseInt(h, 16));
}

function hexStr(arr) {
  return arr.map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ');
}

// Parse TEXT_DATA
const t = extractArray('$9DF2_$9F14');
const strings = [];
let cur = [];
for (const b of t) {
  if (b === 0xFF) { if (cur.length) strings.push(cur); cur = []; }
  else cur.push(b);
}
if (cur.length) strings.push(cur);

// Parse PPU_DATA
const p = extractArray('$9F15_$9FFF');
const recs = [];
let i = 0;
while (i < p.length) {
  if (p[i] === 0xFF) { i++; continue; }
  if (i + 1 >= p.length) break;
  const addr = p[i] | (p[i+1] << 8);
  i += 2;
  const data = [];
  while (i < p.length && p[i] !== 0xFD && p[i] !== 0xFF) data.push(p[i++]);
  const term = i < p.length ? p[i] : null;
  if (term === 0xFD || term === 0xFF) i++;
  recs.push({ addr, data, term: term === 0xFD ? 'FD' : 'FF' });
}

// Generate output
let out = `// ═══════════════════════════════════════════════
// Structured data — pre-parsed from bank-01 raw bytecode streams
// Generated by _convert_protocol_b.mjs
// ═══════════════════════════════════════════════

/** A text string stored as byte array (custom char encoding, not ASCII) */
export type TextString = readonly number[];

/** A PPU nametable upload record — writes data[] to PPU address */
export interface PpuUploadRecord {
  readonly addr: number;         // PPU nametable address (hi<<8|lo)
  readonly data: readonly number[];  // tile bytes to write
  readonly terminator: 'FD' | 'FF'; // FD=next record, FF=end-of-section
}

`;

// TEXT_STRING_DATA
out += `/** $9DF2-$9F14 — 37 strings, $FF-terminated (291 bytes raw) */\n`;
out += `export const TEXT_STRING_DATA: readonly TextString[] = [\n`;
strings.forEach((s, j) => {
  out += `  [${hexStr(s)}], // [${j}] ${s.length}B\n`;
});
out += `];\n\n`;

// PPU_UPLOAD_DATA
out += `/** $9F15-$9FFF — 32 PPU upload records, $FD/$FF-terminated (235 bytes raw) */\n`;
out += `export const PPU_UPLOAD_DATA: readonly PpuUploadRecord[] = [\n`;
recs.forEach((r, j) => {
  const hexAddr = '0x' + r.addr.toString(16).padStart(4, '0').toUpperCase();
  out += `  { addr: ${hexAddr}, data: [${hexStr(r.data)}], terminator: '${r.term}' }, // [${j}]\n`;
});
out += `];\n`;

fs.writeFileSync('game-engine/native-game/tsubasa/banks/prg/bank-01-structured-data.ts', out, 'utf8');
console.log('Done! Written bank-01-structured-data.ts');
console.log(`  TEXT: ${strings.length} strings`);
console.log(`  PPU:  ${recs.length} records`);
