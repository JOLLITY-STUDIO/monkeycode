const BASE = 0x9460;
const SLOTS_PER_FORMATION = 11;
const POS_NAMES = ['GK', 'DF', 'MF', 'FW'];

function le16(lo, hi) { return lo | (hi << 8); }

console.log('═══ 正确解析 — 不检查 0x00 终止,固定读 11 槽 ═══\n');

// 1. 指针表
console.log('指针表 ($9460-$9473):');
const ptrs = [];
for (let i = 0; i < 10; i++) {
    const ptr = le16(data[i * 2], data[i * 2 + 1]);
    ptrs.push(ptr);
    console.log(`  ptr[${i}] = $${ptr.toString(16).toUpperCase()}  (offset=${ptr - BASE})`);
}

// 2. 每个阵型解析 11 槽
console.log('\n═══ 各阵型球员站位 ═══');
for (let fi = 0; fi < ptrs.length; fi++) {
    const off = ptrs[fi] - BASE;
    console.log(`\n阵型 ${fi}: 指针 $${ptrs[fi].toString(16).toUpperCase()}  offset=${off}`);

    let validCount = 0;
    let slotSummary = '';

    for (let s = 0; s < SLOTS_PER_FORMATION; s++) {
        const pos = off + s * 4;
        if (pos + 3 >= data.length) break;

        const pid = data[pos];
        const x = data[pos + 1];
        const y = data[pos + 2];
        const fl = data[pos + 3];

        // 如果连续遇到全零，可能到了数据边界
        if (pid === 0 && x === 0 && y === 0 && fl === 0 && s > 0) {
            // 但不清零 — 可能只是重复数据
        }

        const posType = fl & 0x03;
        const flagsHi = (fl >> 3) & 0x1F;
        const posName = POS_NAMES[posType] || '??';

        if (pid !== 0 || x !== 0 || y !== 0) validCount++;

        slotSummary += `\n    slot[${String(s).padStart(2)}]: playerId=$${pid.toString(16).padStart(2,'0')}(${pid.toString().padStart(3)}) x=$${x.toString(16).padStart(2,'0')}(${x.toString().padStart(3)}) y=$${y.toString(16).padStart(2,'0')}(${y.toString().padStart(3)}) flags=$${fl.toString(16).padStart(2,'0')}(pos=${posName}, hi=${flagsHi})`;
    }

    console.log(`  有效槽位数: ${validCount}/11`);
    if (validCount <= 2) {
        // 只打印概要
        console.log(`  数据: ${data.slice(off, Math.min(off+16, data.length)).map(b => b.toString(16).padStart(2,'0')).join(' ')}`);
    } else {
        console.log(slotSummary);
    }
}

