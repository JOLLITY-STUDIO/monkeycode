// 渲染双 tile 假名 ($A0-$D1) 为 16x8 ASCII art
// 数据从 char-map.ts CHAR_MAP_DOUBLE (hiTile/loTile) 硬编码, 从 chr-bank-00.ts 读 pattern
'use strict';
const fs = require('fs');
const path = require('path');

const chrSrc = fs.readFileSync(path.join(__dirname, '../src/game/data/chr/chr-bank-00.ts'), 'utf-8');
const m = chrSrc.match(/=\s*\[([\s\S]*?)\]/);
const chr = m[1].split(',').map(s => s.trim()).filter(s => /^0x/.test(s)).map(s => parseInt(s, 16));
console.error('chr-bank-00 length:', chr.length, '(expect 8192)');

// (code, hiTile, loTile)
const PAIRS = [
  [0xA0, 0x94, 0x06],[0xA1, 0x94, 0x07],[0xA2, 0x94, 0x08],[0xA3, 0x94, 0x09],
  [0xA4, 0x94, 0x0A],[0xA5, 0x94, 0x0B],[0xA6, 0x94, 0x0C],[0xA7, 0x94, 0x0D],
  [0xA8, 0x94, 0x0E],[0xA9, 0x94, 0x0F],[0xAA, 0x94, 0x10],[0xAB, 0x94, 0x11],
  [0xAC, 0x94, 0x12],[0xAD, 0x94, 0x13],[0xAE, 0x94, 0x14],[0xAF, 0x94, 0x1A],
  [0xB0, 0x94, 0x1B],[0xB1, 0x94, 0x1C],[0xB2, 0x94, 0x1D],[0xB3, 0x94, 0x1E],
  [0xB4, 0x94, 0x46],[0xB5, 0x94, 0x47],[0xB6, 0x94, 0x48],[0xB7, 0x94, 0x49],
  [0xB8, 0x94, 0x4A],[0xB9, 0x94, 0x4B],[0xBA, 0x94, 0x4C],[0xBB, 0x94, 0x4D],
  [0xBC, 0x94, 0x4E],[0xBD, 0x94, 0x4F],[0xBE, 0x94, 0x50],[0xBF, 0x94, 0x51],
  [0xC0, 0x94, 0x52],[0xC1, 0x94, 0x53],[0xC2, 0x94, 0x54],[0xC3, 0x94, 0x5A],
  [0xC4, 0x94, 0x5B],[0xC5, 0x94, 0x5C],[0xC6, 0x94, 0x5D],[0xC7, 0x94, 0x5E],
  [0xC8, 0x95, 0x1A],[0xC9, 0x95, 0x1B],[0xCA, 0x95, 0x1C],[0xCB, 0x95, 0x1D],
  [0xCC, 0x95, 0x1E],[0xCD, 0x95, 0x5A],[0xCE, 0x95, 0x5B],[0xCF, 0x95, 0x5C],
  [0xD0, 0x95, 0x5D],[0xD1, 0x95, 0x5E],
];

function renderTile(tileIdx) {
  const off = tileIdx * 16;
  const rows = [];
  for (let y = 0; y < 8; y++) {
    const p0 = chr[off + y] || 0;
    const p1 = chr[off + 8 + y] || 0;
    let row = '';
    for (let x = 0; x < 8; x++) {
      const bit = 7 - x;
      const v0 = (p0 >> bit) & 1;
      const v1 = (p1 >> bit) & 1;
      const c = (v1 << 1) | v0;
      row += c === 0 ? ' ' : c === 1 ? '.' : c === 2 ? ':' : '#';
    }
    rows.push(row);
  }
  return rows;
}

function renderDouble(hi, lo) {
  const L = renderTile(hi), R = renderTile(lo);
  const rows = [];
  for (let y = 0; y < 8; y++) rows.push(L[y] + R[y]);
  return rows;
}

let out = '';
for (const [code, hi, lo] of PAIRS) {
  out += `=== 0x${code.toString(16).toUpperCase()} hi=0x${hi.toString(16).toUpperCase()} lo=0x${lo.toString(16).toUpperCase()} ===\n`;
  for (const r of renderDouble(hi, lo)) out += '|' + r + '|\n';
  out += '\n';
}

fs.writeFileSync(path.join(__dirname, '_dbl2.txt'), out, 'utf-8');
console.log(out);
