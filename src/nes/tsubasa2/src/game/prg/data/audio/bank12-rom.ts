// SE 指针表（每条 2 字节小端，SE ID → 数据起始 CPU 地址）
// 经 ROM 特征搜索：code_sub.s $8354 处 LDA $8BDA,Y 引用
export const SE_POINTER_TABLE_ADDR = 0x8bda;
export const SE_POINTER_TABLE_LEN = 100;
