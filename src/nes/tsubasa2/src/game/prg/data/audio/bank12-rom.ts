// 音符时值查找表（索引 → tick 数，42 条 1 字节）
export const NOTE_DURATION_TABLE_ADDR = 0x8725;
export const NOTE_DURATION_TABLE_LEN = 42;
// 音符频率查找表（音名索引 → APU 频率 16-bit）
export const NOTE_FREQ_TABLE_ADDR = 0x870d;

/** Bank12Rom — bank12 结构化访问器（替代裸字节索引） */
export class Bank12Rom {
  /** 读一个字节（CPU 地址 → 字节） */
  static readByte(cpuAddr: number): number {
    const off = cpuAddr - BANK12_BASE_ADDR;
    if (off < 0 || off >= BANK12_BYTES.length) return 0;
    return BANK12_BYTES[off];
  }
  /** 读 16-bit 小端（CPU 地址 → 数值） */
  static readU16(cpuAddr: number): number {
    return Bank12Rom.readByte(cpuAddr) | (Bank12Rom.readByte(cpuAddr + 1) << 8);
  }
  /** 读取曲目请求 ID（NSF 曲目号 1-105 → 原版请求 ID 0x03-0x6F） */
  static readSongRequestId(songNo: number): number {
    if (songNo < 1 || songNo > SONG_COUNT) return 0;
    return SONG_REQUEST_IDS[songNo - 1];
  }
  /** 读 SE 指针（SE ID → 数据起始 CPU 地址） */
  static readSePointer(seId: number): number {
    return Bank12Rom.readU16(SE_POINTER_TABLE_ADDR + seId * 2);
  }
  /** 读 BGM 指针（BGM ID → 数据起始 CPU 地址） */
  static readBgmPointer(bgmId: number): number {
    return Bank12Rom.readU16(BGM_POINTER_TABLE_ADDR + bgmId * 2);
  }
  /** 读音符时值（索引 → tick 数） */
  static readNoteDuration(idx: number): number {
    return Bank12Rom.readByte(NOTE_DURATION_TABLE_ADDR + idx);
  }
  /** 读音符频率（音名索引 → APU 频率 16-bit） */
  static readNoteFreq(idx: number): number {
    return Bank12Rom.readU16(NOTE_FREQ_TABLE_ADDR + idx * 2);
  }
}
