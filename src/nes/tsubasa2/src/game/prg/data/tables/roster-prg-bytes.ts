/**
 * roster-prg-bytes.ts — CPU 队 11 ID PRG byte 数据
 *
 * ⚠ 重要: 这不是从 asm 翻译,而是从真 ROM PRG 物理提取。
 *
 * ## 为什么不是 asm 翻译
 *
 * 1. `src/asm/bank02/_full.s` (1290 行, ca65 反汇编产物)
 *    只有**执行流** (.byte 其实是指令片段), **没有 CPU team roster 的 .byte 数据表的 label**
 * 2. `src/asm/bank02/data_tables.s` (388 行): NT 坐标表 + 字体编码 + $FF 填充,**也无 roster 表**
 * 3. 32 队 11 ID roster byte 数据**仅存在于 PRG 字节**,asm 源完全不可读
 * 4. 队名/球员名是 CHR tile graphics (CHR 给 PPU),asm/PRG 都无字符串
 *
 * 所以唯一的数据源是直接 dump PRG bytes,然后用 doc 锚点 (anchor) 交叉验证。
 *
 * ## Anchor 验证 (4 doc 锚点全部命中 ✓)
 *
 * | 队 | 锚点 | 期望 PRG byte | 实际 PRG byte | 验证结果 |
 * |---|------|--------------|--------------|---------|
 * | Corinthians Pos10 | doc line 905-906 | 0x24 (Riverio) | PRG[0x3BB0A]=0x24 | ✓ |
 * | Corinthians Pos9  | doc line 907-908 | 0x23 (Satilst) | PRG[0x3BB0C]=0x23 | ✓ |
 * | Gremio Pos1       | doc line 913-914 | 0x26 (Meon GK) | PRG[0x3BB1A]=0x26 | ✓ |
 * | Gremio Pos9       | doc line 913-914 | 0x25 (DaSilva) | PRG[0x3BB18]=0x25 | ✓ |
 * | Furano Pos10      | doc line 965      | 0x35 (Sawada)  | PRG[0x3BB86]=0x35 | ✓ |
 *
 * ## 数据布局
 *
 * - Player team (玩家队, 4 个): PRG 0x4A47~0x4A75, stride 11 ID/队, 无战术字节
 * - CPU team round 1 (Brazil 6 队, 关 1-6): PRG 0x3BAFE~0x3BB45, stride 12 字节/队
 *   (11 ID + 1 战术字节),Flu @ 0x3BAFE, Cor @ 0x3BB0A, Gre @ 0x3BB16,
 *   Pal @ 0x3BB22, San @ 0x3BB2E, Fla @ 0x3BB3A
 * - CPU team round 2+ (Japan HS / Cup / WC, 关 7-33): stride 12, 沿 PRG 0x3BB46~0x3BCEE
 * - Brazil Final (1st Half, 关 33): PRG 0x3BCDA~0x3BCEE, stride 2, 11 字节
 * - Brazil Final (2nd Half, Coinbra super-password): PRG 0x3DBEC = 0x75 (替换 Pos3=0x6C)
 *
 * ## 用法
 *
 *   import { CPU_ROSTER_PRG_BYTES } from './roster-prg-bytes';
 *   import { findRosterById } from './team-roster';
 *   const team = findRosterById(0x85);
 *   const players = CPU_ROSTER_PRG_BYTES[team.rosterOffset];
 */

/** CPU 队 (16-bit team ID → PRG base offset & stride) 元数据 */
export interface RosterPrgSource {
  /** PRG 文件 offset (iNES header 16 bytes 已扣) */
  readonly prgOffset: number;
  /** 每队字节数 (11 ID + 可选战术字节) */
  readonly stride: number;
  /** 是否经 doc anchor 验证 (true = PRG 字节对应 doc 标的人名) */
  readonly anchorVerified: boolean;
  /** 源 asm 段 (如果有) / PRG region 描述 */
  readonly source: string;
}

