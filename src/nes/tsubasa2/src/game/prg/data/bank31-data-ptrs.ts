/**
 * 读取 16bit LE 指针 (数据块偏移 → 绝对偏移)
 * 对应 asm $E9DA,Y / $E9DB,Y 取表项。
 */
export function readPtrLE16(table: ReadonlyArray<number>, idx: number): number {
  return (table[idx] | (table[idx + 1] << 8)) & 0xFFFF;
}

/**
 * 通过 RamStore 占位构造（保留签名, 后续翻译 $E93D 时使用）
 */
export function ptrDispatch(_store: RamStore, _idx: number): number {
  return readPtrLE16(PTR_TABLE_E9DA, _idx);
}
