/** 双 tile 可读字符子表 ($A0-$D7) */
export const CHAR_MAP_DOUBLE_CHAR: Record<number, string> = (() => {
  const m: Record<number, string> = {};
  for (let c = 0xa0; c <= 0xd7; c++) m[c] = CHAR_MAP_FULL[c] ?? '';
  return m;
})();

