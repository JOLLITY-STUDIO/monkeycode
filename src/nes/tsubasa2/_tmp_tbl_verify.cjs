const fs = require('fs');
const rom = fs.readFileSync('docs/roms/Captain Tsubasa II - Super Striker (Japan).nes');
const off = 0x4010; // bank2 ROM 偏移
// 运行时 $Axxx 地址 → bank2 偏移: 减 0xA000
const A = (addr) => off + (addr - 0xA000);

// NMI_CALLBACK_TABLE at $A491 (24 项 16 位小端)
const cb = [];
for (let i = 0; i < 24; i++) cb.push(rom[A(0xA491) + i * 2] | (rom[A(0xA491) + i * 2 + 1] << 8));
const cbExpected = [0xa4c0, 0xa559, 0xa57b, 0xa581, 0xa5a2, 0xa5a8, 0xa5b0, 0xa5b8, 0xa5bf, 0xa5cd, 0xa5db, 0xa5e8, 0xa602, 0xa61c, 0xa629, 0xa650, 0xa69c, 0xa77a, 0xa782, 0xa78d, 0xa7bd, 0xa7ce, 0xa7d6, 0xa7fa];
const cbOk = cb.every((v, i) => v === cbExpected[i]);
console.log((cbOk ? 'PASS' : 'FAIL') + ' NMI_CALLBACK_TABLE (24 entries)');
if (!cbOk) cb.forEach((v, i) => { if (v !== cbExpected[i]) console.log('  [' + i + '] ROM=' + v.toString(16) + ' TS=' + cbExpected[i].toString(16)); });

// SPRITE_POS_TABLE at $A896 (144 字节)
const sp = Array.from(rom.slice(A(0xA896), A(0xA896) + 144));
const spExpected = [0x80,0x33,0x00,0xa0,0x80,0x33,0x00,0xa8,0x00,0x00,0x60,0x00,0xd0,0x00,0x50,0x01,0x00,0x03,0x00,0x05,0x28,0x06,0x80,0x07,0x00,0x09,0x30,0x0c,0xe0,0x0d,0x70,0x11,0x50,0x13,0x50,0x15,0xb0,0x19,0x60,0x1e,0x60,0x1e,0xd0,0x20,0x48,0x23,0xc8,0x25,0x50,0x28,0xe0,0x2a,0xe0,0x2a,0x78,0x2d,0x18,0x30,0xc8,0x32,0x58,0x38,0x58,0x38,0x30,0x3b,0x10,0x3e,0x40,0x44,0xe8,0x4a,0x20,0x55,0x00,0x59,0x20,0x5d,0x50,0x61,0x90,0x65,0xe0,0x69,0x40,0x6e,0x00,0x73,0xe0,0x77,0xd0,0x7c,0x00,0x82,0x80,0x87,0x80,0x8d,0xe0,0x93,0xd0,0x9a,0xe0,0xa1,0xc0,0xa9,0xc0,0xb1,0xd0,0xb9,0x04,0xc2,0x80,0xcb,0xa0,0xd7,0x00,0xe8];
const spOk = sp.every((v, i) => v === spExpected[i]);
console.log((spOk ? 'PASS' : 'FAIL') + ' SPRITE_POS_TABLE (144B)');
if (!spOk) { const diffs = []; sp.forEach((v, i) => { if (v !== spExpected[i]) diffs.push('[' + i + ']=' + v.toString(16)); }); console.log('  diffs(前20): ' + diffs.slice(0, 20).join(',')); }
