const fs = require('fs');
const p = require('path').join(__dirname, '_tsc_wave2.txt');
let b = fs.readFileSync(p);
let txt = b.toString('utf8');
if (txt.charCodeAt(0) === 0xFEFF) txt = txt.slice(1);
if (txt.includes('\u0000')) txt = b.toString('utf16le');
const errs = txt.split(/\r?\n/).filter(l => l.includes('error TS'));
const prg = errs.filter(l => l.includes('src\\game\\prg') || l.includes('src/game/prg'));
console.log('TOTAL error TS:', errs.length);
console.log('PRG error TS:', prg.length);
if (prg.length) console.log(prg.slice(0, 40).join('\n'));
else if (errs.length) console.log('first 30 non-prg:', errs.slice(0, 30).join('\n'));
else console.log('ZERO ERRORS - clean');
