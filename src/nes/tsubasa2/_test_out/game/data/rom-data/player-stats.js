/** 按 mazongIndex (0-116, 注意不是 ROM ID) 获取能力值原始字节 */
function getPlayerStatsRaw(mazongIndex) {
    return exports.PLAYER_STATS_RAW[mazongIndex] ?? new Array(24).fill(0);
}
/**
 * 按 ROM 角色 ID 获取能力值原始字节。
 * PLAYER_STATS_RAW 按 ROM 角色 ID 排序 (ID 0x01-0x75 → 索引 0-116), 即 romId - 1。
 */
function getPlayerStatsById(romId) {
    const idx = romId - 1;
    if (idx < 0 || idx >= exports.PLAYER_STATS_RAW.length)
        return new Array(24).fill(0);
    return exports.PLAYER_STATS_RAW[idx];
}
/** 按 playerIndex 获取结构化能力值对象 (编码值) */
function getPlayerStats(playerIndex) {
    const raw = getPlayerStatsRaw(playerIndex);
    const obj = {};
    for (let i = 0; i < exports.PLAYER_STAT_FIELDS.length; i++) {
        obj[exports.PLAYER_STAT_FIELDS[i]] = raw[i] ?? 0;
    }
    return obj;
}
/**
 * 按 playerIndex 获取显示用能力值对象 (编码→查表后的真实显示值)
 * 体力查 STAMINA_TABLE, 其他能力查 ABILITY_TABLE
 */
function getPlayerDisplayStats(playerIndex) {
    const raw = getPlayerStatsRaw(playerIndex);
    return {
        stamina: codeToStamina(raw[0]), // 体力 (16bit 查表)
        shot: codeToAbility(raw[1]), // 射门
        pass: codeToAbility(raw[2]), // 传球
        dribble: codeToAbility(raw[3]), // 盘带
        block: codeToAbility(raw[4]), // 阻挡
        tackle: codeToAbility(raw[5]), // 铲球
        intercept: codeToAbility(raw[6]), // 拦截
        raw,
    };
}
/**
 * 按 playerIndex 获取体力 tile IDs (用于 NT 显示)
 * 例: Tsubasa(playerIndex=1) 体力编码 21 → STAMINA_TABLE[21]=642 → tiles [0x3F,0x3E,0x3A,0x3E,0x3B] = "642"
 * FIXME: Tsubasa 真实体力 748, 编码应为 38, 但当前 mazongIndex 偏移待校正
 */
function getPlayerStaminaTiles(playerIndex) {
    const raw = getPlayerStatsRaw(playerIndex);
    const stamina = codeToStamina(raw[0]);
    return numberToTiles(stamina);
}
