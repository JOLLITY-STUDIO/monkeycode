function disasm(cpuStart, len) {
  let p = cpuStart; const end = cpuStart + len; const out = [];
  while (p < end) {
    const i = cpu2prg(p); const b = prg[i];
    const op = OPN[b];
    if (op === undefined) { out.push('$' + p.toString(16).toUpperCase() + ': .byte $' + b.toString(16).padStart(2, '0')); p++; continue; }
    if (IMM.has(b) && !REL.has(b)) {
      out.push('$' + p.toString(16).toUpperCase() + ': ' + op + prg[i + 1].toString(16).padStart(2, '0')); p += 2;
    } else if (ABS.has(b)) {
      const a = (prg[i + 1] | (prg[i + 2] << 8)).toString(16).padStart(4, '0').toUpperCase();
      out.push('$' + p.toString(16).toUpperCase() + ': ' + op + '$' + a); p += 3;
    } else if (REL.has(b)) {
      const rel = prg[i + 1]; const tgt = p + 2 + (rel > 127 ? rel - 256 : rel);
      out.push('$' + p.toString(16).toUpperCase() + ': ' + op + '$' + p.toString(16).toUpperCase().padStart(4, '0') + ' -> $' + tgt.toString(16).toUpperCase()); p += 2;
    } else if (ZP.has(b)) {
      out.push('$' + p.toString(16).toUpperCase() + ': ' + op + prg[i + 1].toString(16).padStart(2, '0')); p += 2;
    } else {
      out.push('$' + p.toString(16).toUpperCase() + ': ' + op); p++;
    }
  }
  return out.join('\n');
}
