function disasm(cpuStart, len, bankFn, label) {
  let p = cpuStart; const end = cpuStart + len; const out = [];
  while (p < end) {
    const i = bankFn(p); const b = prg[i];
    const op = OPN[b];
    if (op === undefined) { out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': .byte $' + b.toString(16).padStart(2,'0')); p++; continue; }
    if (IMM.has(b)) { out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': ' + op + ' #$' + prg[i+1].toString(16).padStart(2,'0').toUpperCase()); p += 2; }
    else if (REL.has(b)) { const rel = prg[i+1]; const tgt = (p + 2 + (rel > 127 ? rel - 256 : rel)) & 0xffff; out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': ' + op + ' -> $' + tgt.toString(16).toUpperCase()); p += 2; }
    else if (ABS.has(b)) { const a = (prg[i+1] | (prg[i+2] << 8)); out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': ' + op + ' $' + a.toString(16).padStart(4,'0').toUpperCase()); p += 3; }
    else if (ZP.has(b)) { out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': ' + op + ' $' + prg[i+1].toString(16).padStart(2,'0').toUpperCase()); p += 2; }
    else { out.push('$' + p.toString(16).toUpperCase().padStart(4,'0') + ': ' + op); p++; }
  }
  return out.join('\n');
}
function hexdump(cpuStart, len, bankFn, label) {
  const off = bankFn(cpuStart);
  const bytes = Array.from(prg.slice(off, off + len));
  const lines = ['===== ' + label + ' $' + cpuStart.toString(16).toUpperCase() + ' (' + len + 'B) =====', JSON.stringify(bytes)];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push('$' + (cpuStart + i).toString(16).toUpperCase().padStart(4,'0') + ': ' + bytes.slice(i, i+16).map(x=>x.toString(16).padStart(2,'0')).join(' '));
  }
  return lines.join('\n');
}
